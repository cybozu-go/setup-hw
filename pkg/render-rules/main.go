package main

import (
	"bytes"
	"go/format"
	"log/slog"
	"os"
	"path/filepath"
	"text/template"

	"sigs.k8s.io/yaml"

	"github.com/cybozu-go/setup-hw/redfish"
)

func main() {
	// Write logs to stderr directly, because github.com/cybozu-go/log imported by
	// the redfish package replaces the output of the default logger.
	slog.SetDefault(slog.New(slog.NewTextHandler(os.Stderr, nil)))

	rules, err := load()
	if err != nil {
		slog.Error("failed to load rules", "error", err)
		os.Exit(1)
	}

	err = render(rules)
	if err != nil {
		slog.Error("failed to render rules", "error", err)
		os.Exit(1)
	}
}

func load() (map[string]*redfish.CollectRule, error) {
	filenames, err := filepath.Glob("rules/*.yml")
	if err != nil {
		return nil, err
	}

	rules := make(map[string]*redfish.CollectRule)
	for _, filename := range filenames {
		data, err := os.ReadFile(filename)
		if err != nil {
			return nil, err
		}

		rule := new(redfish.CollectRule)
		err = yaml.Unmarshal(data, rule)
		if err != nil {
			return nil, err
		}

		err = rule.Validate()
		if err != nil {
			return nil, err
		}

		rules[filepath.Base(filename)] = rule
	}

	return rules, nil
}

func render(rules map[string]*redfish.CollectRule) error {
	var buf bytes.Buffer
	err := tmpl.Execute(&buf, rules)
	if err != nil {
		return err
	}

	src, err := format.Source(buf.Bytes())
	if err != nil {
		return err
	}

	return os.WriteFile("rendered_rules.go", src, 0o644)
}

var tmpl = template.Must(template.New("").Parse(`// Code generated by render-rules.  DO NOT EDIT.
//go:generate go run ../pkg/render-rules

package redfish

import (
	"log"
)

func init() {
	for _, rule := range Rules {
		if err := rule.Compile(); err != nil {
			log.Fatal(err)
		}
	}
}

var Rules = map[string]*CollectRule{
	{{- range $key, $value := . }}
	{{ printf "%q" $key }}: {
		TraverseRule: TraverseRule{
			Root: {{ printf "%q" $value.TraverseRule.Root }},
			ExcludeRules: []string{
				{{- range $value.TraverseRule.ExcludeRules }}
				{{ printf "%q" . }},
				{{- end }}
			},
		},
		MetricRules: []*MetricRule{
			{{- range $value.MetricRules }}
			{
				Path: {{ printf "%q" .Path }},
				PropertyRules: []*PropertyRule{
					{{- range .PropertyRules }}
					{
						Pointer: {{ printf "%q" .Pointer }},
						Name: {{ printf "%q" .Name }},
						Help: {{ printf "%q" .Help }},
						Type: {{ printf "%q" .Type }},
					},
					{{- end }}
				},
			},
			{{- end }}
		},
	},
	{{- end }}
}
`))
